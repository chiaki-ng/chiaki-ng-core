auto AuthMaterial::derive(RegistrationTarget target,
                          std::span<const std::byte> nonce,
                          std::span<const std::byte> morning) noexcept
    -> Expected<AuthMaterial, AuthMaterialError> {
  if (!RpVersion::of(target))
    return unexpected(AuthMaterialError::invalid_target);
  if (nonce.size() != rp_nonce_size)
    return unexpected(AuthMaterialError::invalid_nonce);
  if (morning.size() != rp_key_size)
    return unexpected(AuthMaterialError::invalid_morning);

  AuthMaterial result;
  const bool pre10 = target == RegistrationTarget::ps4_8 ||
                     target == RegistrationTarget::ps4_9;
  const bool ps5 = target == RegistrationTarget::ps5_1;
  const auto& key_a = ps5 ? ps5_auth_table_a : ps4_auth_table_a;
  const auto& key_b = ps5 ? ps5_auth_table_b : ps4_auth_table_b;
  const std::size_t row_a = std::to_integer<std::uint8_t>(nonce[0]) >> 3;
  const std::size_t row_b = std::to_integer<std::uint8_t>(nonce[7]) >> 3;
  for (std::size_t i = 0; i < rp_key_size; ++i) {
    const auto n = std::to_integer<std::uint8_t>(nonce[i]);
    const auto m = std::to_integer<std::uint8_t>(morning[i]);
    std::uint8_t ambassador = 0;
    std::uint8_t bright = 0;
    if (pre10) {
      ambassador = static_cast<std::uint8_t>(n - i - 0x27u) ^ echo_a[i];
      bright = static_cast<std::uint8_t>(m - i + 0x34u) ^
               RegistrationMaterial::echo_b[i] ^ n;
    } else if (ps5) {
      ambassador = static_cast<std::uint8_t>(n - 0x2du - i) ^ key_a[row_a][i];
      bright = static_cast<std::uint8_t>(m + 0x18u + i) ^ n ^ key_b[row_b][i];
    } else {
      ambassador = static_cast<std::uint8_t>(n + 0x36u + i) ^ key_a[row_a][i];
      bright = static_cast<std::uint8_t>((key_b[row_b][i] ^ m) + 0x21u + i) ^ n;
    }
    result.ambassador[i] = std::byte{ambassador};
    result.bright[i] = std::byte{bright};
  }
  return result;
}

auto AuthMaterial::transform(platform::CryptoProvider& crypto,
                             RegistrationTarget target, std::uint64_t counter,
                             CipherDirection direction,
                             std::span<const std::byte> input,
                             std::span<std::byte> output) const
    -> Expected<void, CipherError> {
  return RegistrationCipher::transform(crypto, target, bright.span(),
                                       ambassador.span(), counter, direction,
                                       input, output);
}

