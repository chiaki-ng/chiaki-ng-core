namespace libchiaking::net::protocol::takion::client_detail {

/// @brief How a send is handled when the socket refuses it with would-block,
/// or when datagrams already wait for the socket.
enum class SendClass : std::uint8_t {
  /// @brief Kept in the unsent queue for retry. When the queue is full it
  /// displaces the oldest queued best-effort datagram, or is refused with
  /// send_blocked when none is queued. Handshake chunks, first sends of
  /// reliable fragments, generic data, length-prefixed and trace packets.
  essential,
  /// @brief Kept for retry, and refused with send_blocked when the queue is
  /// full; what it carries is regenerated by later traffic.
  /// Acknowledgements, extended messages such as RTT pongs and metrics
  /// reports, congestion reports, controller and microphone packets.
  best_effort,
  /// @brief Sent at once or refused with send_blocked, and never kept;
  /// refused without a try while datagrams wait, so it cannot overtake them.
  /// Retransmissions, which their timers drive again, and Senkusha probes,
  /// whose send time must be exact.
  immediate,
};

/// @brief What one retry of the unsent queue settled. Plain data.
struct UnsentRetry {
  /// @brief Datagrams the socket took.
  std::size_t sent{};
  /// @brief Datagrams dropped because their deadline passed.
  std::size_t expired{};
  /// @brief Datagrams dropped because the socket failed them or took part
  /// of them.
  std::size_t dropped{};
};

/// @brief Builds, protects and sends every packet a Takion client sends, and
/// never waits for the socket.
///
/// A packet's key position is committed once the socket has taken all of it,
/// or once the datagram is kept for retry, so a refused send that is dropped
/// does not burn keystream and a kept one is never encrypted twice. A send
/// the socket refuses with would-block is kept in a bounded queue of unsent
/// datagrams, as its SendClass allows, and retry_unsent() offers the queue to
/// the socket again. While anything waits, every later send is queued behind
/// it, so datagrams leave in the order they were built. Owned by Client
/// and used only by the call that owns the client; holds references to the
/// client's transport, clock, crypto context and configuration, which outlive
/// it.
class ClientOutbound {
 public:
  /// @brief Makes the send path.
  ///
  /// @param transport The socket; may be null only until the client checks it.
  /// @param clock The monotonic clock.
  /// @param crypto The session's crypto context.
  /// @param config The client's configuration.
  ClientOutbound(net::transport::datagram::DatagramTransport* transport,
                 platform::ClockProvider& clock, CryptoContext& crypto,
                 const ClientConfig& config)
      : transport_(transport),
        clock_(clock),
        crypto_(crypto),
        config_(config),
        unsent_tail_(config.limits.unsent_datagram_capacity == 0
                         ? 0
                         : config.limits.unsent_datagram_capacity - 1) {}

  /// @brief Sets the wire profile packets are framed with.
  ///
  /// @param profile The profile; must outlive its use, or null.
  void set_profile(const WireProfile* profile) noexcept { profile_ = profile; }

  /// @brief Records whether keys are installed.
  ///
  /// @param installed Whether they are.
  void set_crypto_installed(bool installed) noexcept {
    crypto_installed_ = installed;
  }

  /// @brief Restarts the extended header's clock and counter.
  ///
  /// @param now_us The epoch, in monotonic microseconds.
  void begin_extended_epoch(std::uint64_t now_us) noexcept {
    extended_epoch_us_ = now_us;
    tx_extended_counter_ = 0;
  }

  /// @brief Sets until when the datagrams of the next sends may wait in the
  /// unsent queue.
  ///
  /// @param deadline_us Monotonic microseconds, or nothing to keep them until
  ///     they are sent.
  void set_send_deadline(std::optional<std::uint64_t> deadline_us) noexcept {
    send_deadline_us_ = deadline_us;
  }

  /// @brief Reads when a send was last attempted.
  ///
  /// @return Monotonic microseconds.
  std::uint64_t last_send_attempt_us() const noexcept {
    return last_send_attempt_us_;
  }

  /// @brief Offers the unsent queue to the socket, oldest first, without
  /// waiting: stops at the first datagram the socket refuses with
  /// would-block, and drops those whose deadline passed or that the socket
  /// failed.
  ///
  /// @param now_us The current time, in monotonic microseconds.
  /// @return What the retry settled.
  /// @retval ClientError::transport_failure The socket is closed.
  [[nodiscard]] ClientResult<UnsentRetry> retry_unsent(std::uint64_t now_us);
  /// @brief Reads when the unsent queue is next due for a retry.
  ///
  /// @return Monotonic microseconds: the last refusal plus
  ///     `unsent_retry_interval_us`; nothing when nothing waits.
  std::optional<std::uint64_t> next_retry_us() const noexcept;
  /// @brief Counts the datagrams waiting for the socket.
  ///
  /// @return The count.
  std::size_t unsent_count() const noexcept;

  /// @brief Sends one control chunk packet.
  ///
  /// @tparam Chunk A control chunk type.
  /// @param chunk The chunk.
  /// @param handshake_packet Whether it is a handshake chunk, sent unprotected.
  /// @param key_advance Key advance; defaults to the packet's wire size.
  /// @param send_class How a refused send is handled.
  /// @return Nothing.
  /// @retval ClientError See send_encoded_chunk().
  template <class Chunk>
  ClientResult<void> send_chunk(
      Chunk chunk, bool handshake_packet,
      std::optional<std::size_t> key_advance = std::nullopt,
      SendClass send_class = SendClass::essential) {
    return without_datagram(send_encoded_chunk(
        ControlChunkCodec::encode_packet(ControlChunkPacket{std::move(chunk)}),
        handshake_packet, key_advance, 0, send_class));
  }

  /// @brief Sends one reliable fragment in a DATA chunk addressed to the
  /// console.
  ///
  /// @param fragment The fragment.
  /// @param established The association, for the console's tag.
  /// @param encrypted_tail Bytes at the end of the fragment encrypted at the
  ///     packet's key position plus 16, as a direct message's data is; 0 for
  ///     none.
  /// @return The datagram as sent, so it can be resent unchanged.
  /// @retval ClientError::packet_encode_failure The fragment cannot be
  ///     encoded.
  /// @retval ClientError Any send failure; see transmit().
  ClientResult<SecretBytes> send_fragment(
      const OutboundFragment& fragment, const EstablishedHandshake& established,
      std::size_t encrypted_tail = 0);
  /// @brief Resends a recorded datagram as it is, at once or not at all; see
  /// SendClass::immediate.
  ///
  /// @param datagram The bytes first sent.
  /// @return Nothing.
  /// @retval ClientError::send_blocked The socket would block, or
  ///     datagrams wait for it.
  /// @retval ClientError Any socket failure; see offer().
  ClientResult<void> resend_datagram(std::span<const std::byte> datagram);
  /// @brief Sends a DATA_ACK to the console, without duplicate sequences, as
  /// best-effort traffic.
  ///
  /// @param acknowledgement What to acknowledge.
  /// @param established The association, for the console's tag.
  /// @return Nothing.
  /// @retval ClientError Any build or send failure.
  ClientResult<void> send_ack(const DataAcknowledgement& acknowledgement,
                              const EstablishedHandshake& established);
  /// @brief Sends a packet of a family with a payload.
  ///
  /// @param family The family.
  /// @param payload The payload after the headers.
  /// @param handshake_packet Whether to send it unprotected.
  /// @param key_advance Key advance; defaults to the payload size.
  /// @param send_class How a refused send is handled.
  /// @return Nothing.
  /// @retval ClientError See send_packet().
  ClientResult<void> send_plain(
      PacketFamily family, std::span<const std::byte> payload,
      bool handshake_packet,
      std::optional<std::size_t> key_advance = std::nullopt,
      SendClass send_class = SendClass::essential);
  /// @brief Sends an extended message, encrypted when crypto is required, as
  /// best-effort traffic.
  ///
  /// @param message The protobuf body.
  /// @return Nothing.
  /// @retval ClientError::invalid_configuration No profile.
  /// @retval ClientError::unsupported_version The version has no
  ///     extended messages.
  /// @retval ClientError::packet_encode_failure The body exceeds 1024
  ///     bytes.
  /// @retval ClientError::crypto_not_installed Keys are needed but
  /// absent.
  /// @retval ClientError Any send failure.
  ClientResult<void> send_extended_message(std::span<const std::byte> message);
  /// @brief Sends a Senkusha probe at once or not at all; see
  /// SendClass::immediate.
  ///
  /// @param probe The probe.
  /// @return Nothing.
  /// @retval ClientError::invalid_configuration No profile.
  /// @retval ClientError::packet_encode_failure Its size differs from the
  ///     expected size or exceeds the fragment size.
  /// @retval ClientError Any send failure.
  ClientResult<void> send_probe(const SendProbe& probe);
  /// @brief Sends a congestion report as best-effort traffic.
  ///
  /// @param congestion The report.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure It cannot be built or is
  ///     too large.
  /// @retval ClientError Any send failure.
  ClientResult<void> send_congestion(const SendCongestion& congestion);
  /// @brief Sends the controller state, its payload encrypted, as best-effort
  /// traffic.
  ///
  /// @param feedback The state and sequence.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure It cannot be built or is
  ///     too large.
  /// @retval ClientError Any protection or send failure.
  ClientResult<void> send_feedback_state(const SendFeedbackState& feedback);
  /// @brief Sends controller events, their records encrypted, as best-effort
  /// traffic.
  ///
  /// @param feedback The events and sequence.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure They cannot be built or
  ///     are too large.
  /// @retval ClientError Any protection or send failure.
  ClientResult<void> send_feedback_history(const SendFeedbackHistory& feedback);
  /// @brief Sends a caller-built microphone packet, its payload encrypted, as
  /// best-effort traffic.
  ///
  /// @param microphone The packet and payload offset.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure The offset is out of
  ///     range, the family is not audio, or it is too large.
  /// @retval ClientError Any protection or send failure.
  ClientResult<void> send_microphone(const SendMicrophone& microphone);
  /// @brief Sends a length-prefixed packet, never protected.
  ///
  /// @param payload The payload.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure It is too large.
  /// @retval ClientError Any send failure.
  ClientResult<void> send_length_prefixed(std::span<const std::byte> payload);
  /// @brief Sends a GKTRACE packet with a detached tag when crypto is required.
  ///
  /// @param sequence The trace sequence number.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure The version has no trace
  ///     messages, or it cannot be built.
  /// @retval ClientError::crypto_not_installed Keys are needed but
  /// absent.
  /// @retval ClientError::crypto_failure The tag could not be computed.
  /// @retval ClientError Any send failure.
  ClientResult<void> send_trace(std::uint32_t sequence);
  /// @brief Sends a generic-data chunk, its payload encrypted.
  ///
  /// @param chunk The chunk.
  /// @return Nothing.
  /// @retval ClientError::packet_encode_failure The version has no
  ///     generic data, or it cannot be built or is too large.
  /// @retval ClientError Any protection or send failure.
  ClientResult<void> send_generic_data_chunk(const GenericDataChunk& chunk);

 private:
  /// @brief A key position claim, or none when crypto is off.
  using Reservation = std::optional<CryptoContext::LocalReservation>;

  /// @brief Drops the datagram from a send result.
  ///
  /// @param datagram The result.
  /// @return The result without its value.
  static ClientResult<void> without_datagram(
      ClientResult<SecretBytes> datagram);
  /// @brief Sends an encoded control packet body.
  ///
  /// @param encoded The chunk bytes after the type byte, or the encode failure.
  /// @param handshake_packet Whether to send it unprotected.
  /// @param key_advance Key advance; defaults to the packet's wire size.
  /// @param encrypted_tail Bytes at the end encrypted at the packet's key
  ///     position plus 16; 0 to authenticate only.
  /// @param send_class How a refused send is handled.
  /// @return The datagram as sent or kept for retry.
  /// @retval ClientError::packet_encode_failure Encoding failed.
  /// @retval ClientError See send_packet().
  ClientResult<SecretBytes> send_encoded_chunk(
      Expected<SecretBytes, ParseFailure> encoded, bool handshake_packet,
      std::optional<std::size_t> key_advance, std::size_t encrypted_tail = 0,
      SendClass send_class = SendClass::essential);
  /// @brief Frames a packet with its type and any extended header, protects it
  /// unless it is a handshake packet (or plain control and congestion are
  /// allowed before keys), and sends it.
  ///
  /// @param family The family.
  /// @param payload The payload after the headers.
  /// @param handshake_packet Whether to send it unprotected.
  /// @param key_advance Key advance for the crypto context.
  /// @param encrypted_payload_offset Where in the payload encryption starts.
  /// @param cipher_key_position_addition Replaces the family's cipher key
  ///     position addition when given.
  /// @param send_class How a refused send is handled.
  /// @return The datagram as sent or kept for retry.
  /// @retval ClientError::invalid_configuration No profile.
  /// @retval ClientError::packet_encode_failure Framing failed.
  /// @retval ClientError See protect() and transmit().
  ClientResult<SecretBytes> send_packet(
      PacketFamily family, std::span<const std::byte> payload,
      bool handshake_packet, std::size_t key_advance,
      std::size_t encrypted_payload_offset,
      std::optional<std::uint64_t> cipher_key_position_addition = std::nullopt,
      SendClass send_class = SendClass::essential);
  /// @brief Tells the wire size of a control packet.
  ///
  /// @param payload_size Bytes after the type byte.
  /// @return Type byte, payload and envelope.
  std::size_t control_wire_size(std::size_t payload_size) const noexcept;
  /// @brief Protects a framed packet when crypto is required.
  ///
  /// @param packet The packet; changed in place.
  /// @param family Its family.
  /// @param payload_offset Where encryption starts.
  /// @param payload_size How much is encrypted.
  /// @param key_advance Key advance.
  /// @param cipher_key_position_addition Replaces the family's cipher key
  ///     position addition when given.
  /// @return The reservation; none when crypto is off.
  /// @retval ClientError::crypto_not_installed Keys are absent.
  /// @retval ClientError::crypto_failure Protection failed.
  ClientResult<Reservation> protect(
      std::span<std::byte> packet, PacketFamily family,
      std::size_t payload_offset, std::size_t payload_size,
      std::uint64_t key_advance,
      std::optional<std::uint64_t> cipher_key_position_addition = std::nullopt);

  /// @brief How the socket answered an offer.
  enum class Offer : std::uint8_t {
    /// @brief It took the whole datagram.
    sent,
    /// @brief It would block, or datagrams already wait, so it was not
    /// tried.
    refused,
  };

  /// @brief A datagram kept for retry.
  struct UnsentDatagram {
    /// @brief The datagram, protected and wrapped.
    SecretBytes bytes;
    /// @brief How it was sent.
    SendClass send_class{SendClass::essential};
    /// @brief When it is dropped instead of sent, in monotonic microseconds;
    /// empty keeps it until it is sent.
    std::optional<std::uint64_t> expires_us;
  };

  /// @brief Whether datagrams wait for the socket.
  enum class Backlog : std::uint8_t {
    /// @brief Nothing waits; sends go straight to the socket.
    clear,
    /// @brief Datagrams wait; every new send is queued behind them.
    waiting,
  };

  /// @brief Wraps the envelope and offers the datagram to the socket; keeps
  /// it for retry when the socket refuses it and its class allows. Commits
  /// the key position when the socket took the datagram or it was kept.
  ///
  /// @param wire The packet.
  /// @param reservation Its key position claim.
  /// @param send_class How a refused send is handled.
  /// @return The datagram as sent or kept.
  /// @retval ClientError::packet_encode_failure The envelope failed.
  /// @retval ClientError::send_blocked It was refused and not kept.
  /// @retval ClientError::crypto_failure The commit failed.
  /// @retval ClientError See offer().
  ClientResult<SecretBytes> transmit(std::span<const std::byte> wire,
                                     Reservation reservation,
                                     SendClass send_class);
  /// @brief Writes a datagram once, without waiting; refuses it untried
  /// while datagrams wait for the socket.
  ///
  /// @param datagram The bytes.
  /// @return Whether the socket took it or refused it.
  /// @retval ClientError::short_send The socket took part of it.
  /// @retval ClientError::transport_failure The socket is closed.
  /// @retval ClientError::send_dropped Any other socket failure.
  ClientResult<Offer> offer(std::span<const std::byte> datagram);
  /// @brief Makes room in the unsent queue for a datagram of a class,
  /// displacing the oldest queued best-effort datagram for an essential one
  /// when the queue is full. The order of what remains is kept.
  ///
  /// @param send_class The class of the datagram to keep.
  /// @return Whether it may be kept.
  bool make_room(SendClass send_class);
  /// @brief Appends a datagram to the unsent queue; make_room() must have
  /// allowed it.
  ///
  /// @param datagram The datagram.
  /// @param send_class How it was sent.
  void keep_unsent(SecretBytes datagram, SendClass send_class);
  /// @brief Maps a socket failure to the client's error.
  ///
  /// @param error The failure; not would-block.
  /// @return transport_failure for a closed socket, send_dropped otherwise.
  static ClientError send_error(
      net::transport::datagram::TransportError error) noexcept;

  /// @brief The socket.
  net::transport::datagram::DatagramTransport* transport_;
  /// @brief The monotonic clock.
  platform::ClockProvider& clock_;
  /// @brief The session's crypto context.
  CryptoContext& crypto_;
  /// @brief The client's configuration.
  const ClientConfig& config_;
  /// @brief The wire profile packets are framed with.
  const WireProfile* profile_{};
  /// @brief Whether keys are installed.
  bool crypto_installed_{};
  /// @brief Builds the next extended header: microseconds since the epoch and
  /// the next counter value.
  ///
  /// @return The header.
  ExtendedPacketHeader next_extended_header() noexcept;

  /// @brief Extended headers sent since the epoch.
  std::uint32_t tx_extended_counter_{};
  /// @brief When the extended header's clock started, in monotonic
  /// microseconds.
  std::uint64_t extended_epoch_us_{};
  /// @brief Until when datagrams of the current sends may wait for retry.
  std::optional<std::uint64_t> send_deadline_us_{};
  /// @brief When a send was last attempted, in monotonic microseconds.
  std::uint64_t last_send_attempt_us_{};
  /// @brief When the socket last refused a send, in monotonic microseconds.
  std::uint64_t refused_at_us_{};
  /// @brief Whether datagrams wait for the socket.
  Backlog backlog_{Backlog::clear};
  /// @brief The oldest waiting datagram, offered first; set whenever the
  /// backlog is waiting.
  std::optional<UnsentDatagram> unsent_head_;
  /// @brief The datagrams waiting behind the head, oldest first.
  libchiaking::containers::BoundedQueue<UnsentDatagram> unsent_tail_;

 private:
  /// @brief The DATA chunk flag marking a message's final fragment.
  static constexpr std::uint8_t data_end_flag = 0x01;
};

}  // namespace libchiaking::net::protocol::takion::client_detail
