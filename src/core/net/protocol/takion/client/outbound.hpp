/// @file
/// @brief Declares ClientOutbound, the Takion client's send path: it frames
/// each packet for the active version, protects it when crypto is on, wraps
/// the envelope and writes it to the socket.
#pragma once

#include "libchiaking/platform/runtime/clock_provider.hpp"
#include "src/core/net/protocol/takion/client/lifecycle.hpp"
