  static auto message(control::Message item)
      -> std::function<InvitedPlayer::Effects(Rig&)> {
    return
        [item = std::make_shared<control::Message>(std::move(item))](Rig& rig) {
          return rig.receive(test_support::kakusan::Messages::clone(*item));
        };
  }

